/** Parse a raw WS frame. Returns null on invalid JSON or schema mismatch. */
export function parseMessage<T>(schema: z.ZodType<T>, raw: string | ArrayBuffer | Uint8Array): T | null {
  let text: string;
  if (typeof raw === "string") text = raw;
  else text = new TextDecoder().decode(raw instanceof ArrayBuffer ? new Uint8Array(raw) : raw);
  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    return null;
  }
  const result = schema.safeParse(json);
  return result.success ? result.data : null;
}
