// ---------- Runner -> Hub ----------

const runMsg = { run_id: z.string(), seq: z.number().int().nonnegative() };

export const RunnerToHub = z.discriminatedUnion("type", [
  z.object({
    type: z.literal("hello"),
    protocol: z.number().int(),
    name: z.string(),
    version: z.string(),
    capabilities: RunnerCapabilities,
    /** Runs this runner is still executing (used to reconcile after reconnects). */
    active_runs: z.array(z.string()),
  }),
  z.object({ type: z.literal("heartbeat"), active_runs: z.array(z.string()) }),
  z.object({ type: z.literal("run.accepted"), ...runMsg }),
  z.object({ type: z.literal("run.event"), ...runMsg, event: RunnerEventBody }),
  z.object({
    type: z.literal("run.done"),
    ...runMsg,
    status: z.enum(["done", "cancelled", "failed"]),
    error: z.string().optional(),
    tokens_in: z.number().int().nonnegative(),
    tokens_out: z.number().int().nonnegative(),
  }),
  /** A tool call needs the owner. `approval_id` is generated by the runner so retries are idempotent. */
  z.object({
    type: z.literal("run.approval_request"),
    ...runMsg,
    approval_id: z.string().min(8).max(64),
    action: z.string().max(500),
    risk_level: RiskLevel,
    details: z.record(z.string(), z.unknown()),
  }),
  /** Queue a job for another agent. Sequenced, so it survives reconnects and is applied once. */
  z.object({
    type: z.literal("run.handoff"),
    ...runMsg,
    to_agent: z.string().min(1).max(64),
    title: z.string().min(1).max(200),
    input: z.record(z.string(), z.unknown()),
    reason: z.string().max(500),
    project_id: z.string().nullable(),
  }),
  /** Marketing saved a content draft for the owner to review. Sequenced: applied once. */
  z.object({
    type: z.literal("run.draft"),
    ...runMsg,
    project_id: z.string(),
    platform: Platform,
    kind: DraftKind,
    title: z.string().max(200),
    body: z.string().min(1).max(20_000),
    self_check: SelfCheck,
  }),
  /** A user-facing note for a released change (Coder after a merge). Hub writes the feature log and emits feature.released. */
  z.object({ type: z.literal("run.feature_note"), ...runMsg, project_id: z.string(), note: FeatureNoteInput }),
  /** A long-term memory note from the agent (spec Phase 5 "agent memory"). */
  z.object({ type: z.literal("run.memory"), ...runMsg, target: z.enum(["memory", "user"]), ops: z.array(MemoryOp).min(1).max(20) }),
  /** The agent proposes a skill change; the owner approves it in the Skills inbox. `content` is the full new SKILL.md (empty for delete). */
  z.object({
    type: z.literal("run.skill"),
    ...runMsg,
    name: SkillName,
    action: z.enum(["create", "patch", "delete"]),
    content: z.string().max(20_000),
    reason: z.string().max(500),
  }),
  /** After a reconnect: "what happened to these?" The hub answers with approval.decision for decided ones. */
  z.object({ type: z.literal("approval.poll"), approval_ids: z.array(z.string()) }),
]);
export type RunnerToHub = z.infer<typeof RunnerToHub>;
export type RunnerRunMessage = Extract<RunnerToHub, { seq: number }>;

// ---------- Hub -> Runner ----------

/** What Marketing may read (spec §8.4 "Inputs and ONLY these"). */
export const ProjectContext = z.object({
  /** e.g. "Saturday, 17 October 2026" in Asia/Kuala_Lumpur, for seasonal promos. */
  today: z.string(),
  projects: z.array(
    z.object({
      id: z.string(),
      slug: z.string(),
      name: z.string(),
      live_url: z.string().nullable(),
      brief: ProjectBrief.nullable(),
      features: z.array(z.object({ title: z.string(), user_facing_note: z.string(), released_at: z.string() })),
      /** Recent decided drafts with the owner's edits and feedback: the agent's style memory. */
      past_drafts: z.array(
        z.object({
          platform: Platform,
          kind: DraftKind,
          status: DraftStatus,
          body: z.string(),
          original_body: z.string(),
          owner_feedback: z.string().nullable(),
        }),
      ),
    }),
  ),
});
export type ProjectContext = z.infer<typeof ProjectContext>;

export const RunAssignment = z.object({
  run_id: z.string(),
  job: z.object({
    id: z.string(),
    type: z.string(),
    title: z.string(),
    input: z.record(z.string(), z.unknown()),
    project_id: z.string().nullable(),
  }),
  agent: z.object({
    id: z.string(),
    slug: z.string(),
    name: z.string(),
    model: z.string(),
    system_prompt: z.string(),
    tools: z.array(z.string()),
    config: AgentConfig,
    permission_level: PermissionLevel,
  }),
  provider: ProviderRuntimeConfig,
  /** Only sent when the agent has Gitea-related tools and Gitea is configured. */
  gitea: z.object({ url: z.string(), token: z.string() }).nullable(),
  /** Enabled projects (Tester and Pak Guard check their live URLs; Coder uses repo URLs). */
  projects: z.array(z.object({ id: z.string(), slug: z.string(), name: z.string(), live_url: z.string().nullable(), repo_url: z.string().nullable() })),
  /** Enabled agents this one may hand off to. */
  handoff_targets: z.array(z.object({ slug: z.string(), name: z.string(), role: z.string() })),
  /** Briefs, feature log and past drafts: only sent to agents with project-knowledge tools (Marketing). */
  project_context: ProjectContext.nullable().default(null),
  /** Tokens the agent may still use today (null = no daily limit). The runtime stops when it runs out. */
  budget_left_tokens: z.number().int().nullable().default(null),
  /** The agent's newest memory notes, oldest first. */
  memory: z.object({ memory: z.array(z.string()), user: z.array(z.string()) }).default({ memory: [], user: [] }),
  /** When on, memory writes wait for the owner (Hermes `memory.write_approval`). */
  memory_write_approval: z.boolean().default(false),
  /** Approved skills. Only names + descriptions go into the prompt; the content is read with skill_view. */
  skills: z.array(z.object({ name: z.string(), description: z.string(), content: z.string() })).default([]),
});
export type RunAssignment = z.infer<typeof RunAssignment>;

